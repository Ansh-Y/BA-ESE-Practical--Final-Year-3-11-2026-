import nltk

# Download required NLTK resources
nltk.download('punkt_tab')
nltk.download('stopwords')
nltk.download('averaged_perceptron_tagger_eng')

from nltk.tokenize import word_tokenize, sent_tokenize
from nltk.corpus import stopwords
from nltk import pos_tag

# Accept paragraph from user
text = input("Enter a paragraph: ")

# 1. Sentence Segmentation
sentences = sent_tokenize(text)
print("\n1. Sentence Segmentation:")
print(sentences)

# 2. Tokenization
tokens = word_tokenize(text)
print("\n2. Tokenization:")
print(tokens)

# 3. Stop Word Removal
stop_words = set(stopwords.words('english'))
filtered = [
    word for word in tokens
    if word.lower() not in stop_words and word.isalnum()
]
print("\n3. Stop Word Removal:")
print(filtered)

# 4. Grammar Processing (POS Tagging)
tags = pos_tag(tokens)
print("\n4. POS Tagging:")
print(tags)

# Explanation
print("\n--- NLP COMPONENTS EXPLANATION ---")
print("1. Sentence Segmentation: Divides the paragraph into individual sentences.")
print("2. Tokenization: Splits text into individual words and punctuation marks.")
print("3. Stop Word Removal: Removes common words such as 'is', 'the', 'and', etc.")
print("4. POS Tagging: Identifies grammatical categories such as nouns, verbs, and adjectives.")

from nltk.stem import WordNetLemmatizer
nltk.download('wordnet')

lemmatizer = WordNetLemmatizer()

lemmas = [lemmatizer.lemmatize(w, pos='v') for w in filtered]
print("\nLemmatized Text:")
print(lemmas)

